#!/usr/bin/env node
// Dependency-free repository leak scan (plain `node scripts/leak-scan.mjs [root]`).

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.argv[2] || process.cwd());

const SKIP_DIRS = new Set(["node_modules", ".git", ".wrangler", "dist", "coverage"]);
const TEXT_EXTENSIONS = new Set([
	".ts", ".tsx", ".js", ".mjs", ".cjs", ".json", ".jsonc",
	".md", ".html", ".txt", ".yml", ".yaml", ".toml",
]);
// This harness and the smoke script must embed the search needles themselves, so neither is a scan target.
// worker-configuration.d.ts is generated by Wrangler and contains an unrelated Cloudflare RateLimit binding.
const SKIP_FILES = new Set(["package-lock.json", "scripts/leak-scan.mjs", "scripts/smoke.mjs", "worker-configuration.d.ts"]);
const FORBIDDEN_TOKENS = ["crt.sh", "crt", "output=json", "daily quota", "rate limit"];
// src/lookup.ts may hold more than one private endpoint constant (primary + fallback); all are permitted there.
const UPSTREAM_CONSTANT_FILE = "src/lookup.ts";
const README_FILE = "README.md";

function walk(directory, acc = []) {
	let entries;
	try {
		entries = fs.readdirSync(directory, { withFileTypes: true });
	} catch {
		return acc;
	}
	for (const entry of entries) {
		const full = path.join(directory, entry.name);
		if (entry.isDirectory()) {
			if (SKIP_DIRS.has(entry.name)) continue;
			walk(full, acc);
		} else if (entry.isFile()) {
			acc.push(full);
		}
	}
	return acc;
}

function toRel(file) {
	return path.relative(root, file).split(path.sep).join("/");
}

const found = new Map();

function collectMatches(rel, content, allowUpstreamConstant) {
	content.split(/\r?\n/).forEach((line, index) => {
		const lowered = line.toLowerCase();
		const tokens = FORBIDDEN_TOKENS.filter((token) => {
			if (!lowered.includes(token)) return false;
			if (allowUpstreamConstant && (token === "crt" || token === "crt.sh" || token === "output=json")) return false;
			return true;
		});
		if (tokens.length === 0) return;
		const key = `${rel}:${index + 1}`;
		const existing = found.get(key);
		if (existing) {
			for (const token of tokens) existing.tokens.add(token);
		} else {
			found.set(key, { file: rel, line: index + 1, tokens: new Set(tokens) });
		}
	});
}

let scanned = 0;

for (const file of walk(root)) {
	const rel = toRel(file);
	if (rel === README_FILE) continue; // Scanned explicitly below with zero tolerance.
	if (SKIP_FILES.has(rel) || path.basename(file) === "package-lock.json") continue;
	if (!TEXT_EXTENSIONS.has(path.extname(file).toLowerCase())) continue;
	let content;
	try {
		content = fs.readFileSync(file, "utf8");
	} catch {
		continue;
	}
	scanned += 1;
	collectMatches(rel, content, rel === UPSTREAM_CONSTANT_FILE);
}

// README.md is scanned explicitly with zero tolerance for every token.
const readmePath = path.join(root, README_FILE);
if (fs.existsSync(readmePath) && fs.statSync(readmePath).isFile()) {
	let content;
	try {
		content = fs.readFileSync(readmePath, "utf8");
		scanned += 1;
		collectMatches(README_FILE, content, false);
	} catch {
		// Unreadable README is reported via the explicit check below.
	}
} else {
	console.log("[warn] README.md not found at repository root");
}

console.log(`[scan] root: ${root}`);
console.log(`[scan] files scanned: ${scanned}`);
const ordered = [...found.values()].sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
for (const match of ordered) {
	console.log(`[leak] ${match.file}:${match.line} tokens=[${[...match.tokens].join(", ")}]`);
}

if (ordered.length === 0) {
	console.log("LEAK SCAN PASS");
	process.exit(0);
} else {
	console.log(`LEAK SCAN FAIL (${ordered.length} matches)`);
	process.exit(1);
}
